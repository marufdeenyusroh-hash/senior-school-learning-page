function showTopic(topic) {
    const container = document.getElementById("videoContainer");

    container.innerHTML = `
        <h2>${topic.title}</h2>
        ${topic.videos.map(video => `
            <iframe
                width="560"
                height="315"
                src="${video.url}"
                title="YouTube video"
                frameborder="0"
                allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
                allowfullscreen>
            </iframe>
            <br><br>
        `).join("")}
    `;
}
let currentSubject = "";
let currentLevel = "";

function loadVideosFromDropdown(){

  const subject =
    document.getElementById("subjectSelect").value;

  loadVideos(subject);
}

function loadVideos(subject){

  currentSubject = subject;

  const list = videos[subject] || [];

  const container = document.getElementById("videoList");
  container.innerHTML = "";

  if(list.length === 0){
    container.innerHTML = "<p>No videos available for this selection</p>";
    document.getElementById("player").src = "";
    return;
  }

  list.forEach((video, index) => {

    container.innerHTML += `
      <div class="video-item ${index===0?'active':''}"
           onclick="selectTopic(${index}, this)">
        ${video.title}
      </div>
    `;

  });

  const firstVideo =
    list[0].url ||
    list[0].videos?.[0]?.url ||
    "";

document.getElementById("player").src = firstVideo;}
function selectTopic(index, element){

  const topic =
    videos[currentSubject][index];

  if(topic.videos){

    document.getElementById("player").src =
      topic.videos[0].url;

    showTopic(topic);

  }else{

    document.getElementById("player").src =
      topic.url;

    document.getElementById("videoContainer").innerHTML = "";
  }

  document.querySelectorAll(".video-item")
    .forEach(el => el.classList.remove("active"));

  element.classList.add("active");
}